"""
Experiment H: Structural Hamming Distance (direction-sensitive) for the core
cluster-decomposition grid.

P1-3 closure: the main paper scores F1 with direction IGNORED. This script adds
the direction-sensitive SHD so we can show per-cluster also beats baseline on
direction (lower SHD), not just on edge existence.

CRITICAL: to keep F1 identical to Table S1/S7 (which come from
overnight_checkpoint.json generated by overnight_master.py), this script
replicates overnight_master.py's EXACT data-generation and NOTEARS settings:
  - make_heterogeneous_dags(50, 3, 1.0, s0p, seed=42 + s)   # per-seed DAG seed
  - sample_heterogeneous(W_list, n, 1.0, seed=1000 + s)
  - sample_sem uses eps = rng.randn(n, d) ONCE (NOT per-column randn)
  - run_notears_np outer=15, inner=100, lr=0.002, l1=0.01, thresh=0.3
  - KMeans(n_clusters=3, random_state=s, n_init=10)

Grid: s0_private in {0.2,0.4,0.8} x n in {200,300,600} x 10 seeds
      x {baseline, per-cluster, oracle}. Records F1 + SHD (with decomposition).

Checkpoint: ../../data/h_shd_grid_checkpoint.json (unit-granular).
"""
import os, sys, json, time, warnings, argparse
warnings.filterwarnings('ignore')
import numpy as np
import torch
from sklearn.cluster import KMeans
os.environ['KMP_DUPLICATE_LIB_OK'] = 'TRUE'
os.environ['OMP_NUM_THREADS'] = '2'
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')

CHECKPOINT = r'../../data/h_shd_grid_checkpoint.json'

# ================= data generation (identical to overnight_master.py) =================
def make_dag(d, s0, seed):
    rng = np.random.RandomState(seed)
    W = np.zeros((d, d))
    for j in range(d):
        for i in range(j):
            if rng.rand() < s0 / max(d - 1, 1):
                W[j, i] = rng.uniform(0.5, 1.0) * rng.choice([-1.0, 1.0])
    return W

def make_heterogeneous_dags(d, K_true, s0_shared, s0_private, seed):
    rng = np.random.RandomState(seed)
    W_shared = make_dag(d, s0_shared, seed)
    W_list = []
    for k in range(K_true):
        W_k = W_shared.copy()
        for j in range(d):
            for i in range(j):
                if W_shared[j, i] == 0 and rng.rand() < s0_private / max(d - 1, 1):
                    W_k[j, i] = rng.uniform(0.5, 1.0) * rng.choice([-1.0, 1.0])
        W_list.append(W_k)
    return W_list

def sample_sem(W, n, sigma, seed):
    """IMPORTANT: eps generated as a single (n,d) matrix, matching overnight_master."""
    d = W.shape[0]
    rng = np.random.RandomState(seed)
    X = np.zeros((n, d))
    eps = rng.randn(n, d) * sigma
    for j in range(d):
        X[:, j] = X @ W[j, :] + eps[:, j]
    return X

def sample_heterogeneous(W_list, n_total, sigma, seed):
    K = len(W_list)
    Xs, labels = [], []
    for k, W_k in enumerate(W_list):
        nk = n_total // K + (1 if k < n_total % K else 0)
        Xs.append(sample_sem(W_k, nk, sigma, seed + k * 1000))
        labels.extend([k] * nk)
    X = np.vstack(Xs).astype(np.float32)
    X = (X - X.mean(0)) / (X.std(0) + 1e-8)
    return X, np.array(labels)

def true_edge_set(W_list):
    d = W_list[0].shape[0]
    edges = set()
    for W in W_list:
        for j in range(d):
            for i in range(j):
                if W[j, i] != 0:
                    edges.add((i, j))
    return edges

# ================= NOTEARS core (identical to overnight_master.py) =================
def run_notears_np(X, outer, inner, seed=0):
    torch.manual_seed(seed); np.random.seed(seed)
    d = X.shape[1]
    Xg = torch.tensor(X, dtype=torch.float32, device=device)
    W = torch.zeros(d, d, device=device, requires_grad=True)
    rho, alpha = 1.0, 0.0
    opt = torch.optim.Adam([W], lr=0.002)
    for o in range(outer):
        for _ in range(inner):
            opt.zero_grad()
            M = torch.eye(d, device=device) - W
            sq = (Xg @ M.T).pow(2)
            loss_d = sq.mean()
            h = torch.trace(torch.linalg.matrix_exp(W * W)) - d
            loss = loss_d + 0.5 * rho * h * h + alpha * h + 0.01 * torch.sum(torch.abs(W))
            loss.backward()
            torch.nn.utils.clip_grad_norm_(W, 10.0)
            opt.step()
        with torch.no_grad():
            hv = (torch.trace(torch.linalg.matrix_exp(W * W)) - d).item()
        if abs(hv) < 1e-8: break
        if abs(hv) > 1e-6: alpha = alpha + rho * hv
        rho = min(5 * rho, 1e12)
        if torch.isnan(W).any() or torch.isinf(W).any(): break
    return W.detach().cpu().numpy()

def W_to_edges(W, thresh=0.3):
    d = W.shape[0]
    return {(i, j) for j in range(d) for i in range(j) if abs(W[j, i]) > thresh}

def cluster_union_edges(X, labels, outer, inner, seed):
    d = X.shape[1]
    edges = set()
    for c in np.unique(labels):
        mask = labels == c
        if mask.sum() < d + 1:
            continue
        Wc = run_notears_np(X[mask], outer, inner, seed + int(c) * 1000)
        edges |= W_to_edges(Wc)
    return edges

# ================= evaluation =================
def score_undirected(pred, true):
    pred = set(pred); true = set(true)
    tp = len(pred & true); fp = len(pred - true); fn = len(true - pred)
    P = tp / (tp + fp) if (tp + fp) > 0 else 0.0
    R = tp / (tp + fn) if (tp + fn) > 0 else 0.0
    F1 = 2 * P * R / (P + R) if (P + R) > 0 else 0.0
    return F1, P, R, tp, fp, fn, len(pred)

def score_directed(pred, true):
    """Structural Hamming Distance (direction-sensitive)."""
    pred = set(pred); true = set(true)
    missing = len(true - pred)                      # true edge not recovered
    extra = len(pred - true)                        # spurious edge
    reversed_ = sum(1 for (i, j) in pred if (j, i) in true)
    shd = missing + extra + reversed_
    return shd, missing, extra, reversed_

def load_cp(path):
    return json.load(open(path, encoding='utf-8')) if os.path.exists(path) else {}

def save_cp(cp, path):
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        json.dump(cp, f)
    os.replace(tmp, path)

def _key(s0p, n, s, m):
    return f's0p{s0p}_n{n}/seed{s}/{m}'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--seeds', type=int, default=10)
    ap.add_argument('--outer', type=int, default=15)
    ap.add_argument('--inner', type=int, default=100)
    ap.add_argument('--limit', type=int, default=0)
    args = ap.parse_args()

    cp = load_cp(CHECKPOINT)
    s0_priv_list = [0.2, 0.4, 0.8]
    n_list = [200, 300, 600]
    methods = ['baseline', 'percluster', 'oracle']

    units = [(s0p, n, s, m)
             for s0p in s0_priv_list for n in n_list
             for s in range(args.seeds) for m in methods]
    todo = [u for u in units if _key(*u) not in cp]
    print(f'SHD grid: {len(units)} units, {len(todo)} todo, device={device}', flush=True)

    done = 0
    t0 = time.time()
    for (s0p, n, s, m) in todo:
        if args.limit and done >= args.limit:
            print(f'[limit {args.limit}]', flush=True)
            break
        key = _key(s0p, n, s, m)
        W_list = make_heterogeneous_dags(50, 3, 1.0, s0p, seed=42 + s)
        X, labels_true = sample_heterogeneous(W_list, n, 1.0, seed=1000 + s)
        te = true_edge_set(W_list)
        if m == 'baseline':
            edges = W_to_edges(run_notears_np(X, args.outer, args.inner, s))
        elif m == 'percluster':
            labels_km = KMeans(n_clusters=3, random_state=s, n_init=10).fit(X).labels_
            edges = cluster_union_edges(X, labels_km, args.outer, args.inner, s)
        else:  # oracle
            edges = cluster_union_edges(X, labels_true, args.outer, args.inner, s)
        F1, P, R, tp, fp, fn, ne = score_undirected(edges, te)
        shd, miss, extra, rev = score_directed(edges, te)
        cp[key] = dict(f1=round(F1, 4), precision=round(P, 4), recall=round(R, 4),
                       tp=tp, fp=fp, fn=fn, n_edges=ne,
                       shd=shd, shd_missing=miss, shd_extra=extra, shd_reversed=rev)
        save_cp(cp, CHECKPOINT)
        done += 1
        print(f'[{done}/{len(todo)}] {key}: F1={F1:.3f} SHD={shd:>4} '
              f'(miss{miss} extra{extra} rev{rev}) | {time.time()-t0:.0f}s', flush=True)

    _summarize(cp, s0_priv_list, n_list, methods, args.seeds)

def _summarize(cp, s0p_list, n_list, methods, seeds):
    from scipy import stats
    print('\n=== SHD SUMMARY (mean over seeds) ===', flush=True)
    print(f'{"config":<14}{"base F1/SHD":<16}{"pcl F1/SHD":<16}{"orac F1/SHD":<16}'
          f'{"SHD gain(pcl-base)":<12}t/p', flush=True)
    for s0p in s0p_list:
        for n in n_list:
            row = []
            ok = True
            for m in methods:
                keys = [_key(s0p, n, s, m) for s in range(seeds)]
                if any(k not in cp for k in keys):
                    ok = False
                    row.append(f'{m}=INCOMPLETE')
                    continue
                f1 = np.mean([cp[k]['f1'] for k in keys])
                shd = np.mean([cp[k]['shd'] for k in keys])
                row.append(f'{m}={f1:.3f}/{shd:.0f}')
            if not ok:
                print(f's0p{s0p}_n{n}: ' + ' '.join(row), flush=True)
                continue
            b = [cp[_key(s0p, n, s, 'baseline')]['shd'] for s in range(seeds)]
            p = [cp[_key(s0p, n, s, 'percluster')]['shd'] for s in range(seeds)]
            d = np.array(p) - np.array(b)
            t = float(d.mean() / (d.std(ddof=1) / np.sqrt(len(d)))) if d.std(ddof=1) > 0 else 0.0
            pval = float(2 * stats.t.sf(abs(t), df=len(d) - 1))
            print(f's0p{s0p}_n{n}: ' + ' '.join(row) +
                  f'  SHD_gain={d.mean():+.1f}  t={t:.2f} p={pval:.3g}', flush=True)

if __name__ == '__main__':
    t0 = time.time(); main(); print(f'Total {time.time()-t0:.0f}s', flush=True)
